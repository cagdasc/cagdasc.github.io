import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const outBaseDir = path.join(rootDir, 'dist-lumentv');
const webOutDir = path.join(outBaseDir, 'web');
const generatedAssetsPath = path.join(outBaseDir, 'generated-assets.ts');
const generatedEntryPath = path.join(outBaseDir, 'entry.ts');
const standaloneModulePath = path.join(rootDir, 'graveyard', 'lumentv', 'server', 'standalone.ts');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.mjs': 'application/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
};

function parseCliFlags(argv) {
  let target = '';
  let outfile = '';
  let skipVite = false;
  let bundleOnly = false;

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--skip-vite') {
      skipVite = true;
    } else if (arg === '--bundle-only') {
      bundleOnly = true;
    } else if (arg === '--target' && argv[i + 1]) {
      target = argv[++i];
    } else if (arg.startsWith('--target=')) {
      target = arg.slice('--target='.length);
    } else if (arg === '--outfile' && argv[i + 1]) {
      outfile = argv[++i];
    } else if (arg.startsWith('--outfile=')) {
      outfile = arg.slice('--outfile='.length);
    }
  }

  return { target, outfile, skipVite, bundleOnly };
}

function collectFiles(dir, baseDir = dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const results = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectFiles(fullPath, baseDir));
    } else if (entry.isFile()) {
      const rel = '/' + path.relative(baseDir, fullPath).replace(/\\/g, '/');
      results.push({ routePath: rel, fullPath });
    }
  }
  return results;
}

function generateEntryModules() {
  if (!fs.existsSync(webOutDir)) {
    throw new Error(`Expected standalone web build directory at ${webOutDir}`);
  }

  const files = collectFiles(webOutDir);
  const lines = [
    '// Auto-generated by scripts/build-lumentv.mjs — do not edit manually.',
    'export const EMBEDDED_ASSETS: Record<string, { contentType: string; base64: string }> = {',
  ];

  for (const file of files) {
    const ext = path.extname(file.fullPath).toLowerCase();
    const contentType = MIME_TYPES[ext] || 'application/octet-stream';
    const base64 = fs.readFileSync(file.fullPath).toString('base64');
    lines.push(
      `  ${JSON.stringify(file.routePath)}: { contentType: ${JSON.stringify(contentType)}, base64: ${JSON.stringify(base64)} },`
    );
  }

  lines.push('};');
  lines.push('');
  fs.writeFileSync(generatedAssetsPath, lines.join('\n'), 'utf8');

  const relStandalone = path
    .relative(outBaseDir, standaloneModulePath)
    .replace(/\\/g, '/')
    .replace(/\.ts$/, '');
  const entrySource = [
    `import { startStandaloneServer } from ${JSON.stringify(relStandalone)};`,
    `import { EMBEDDED_ASSETS } from './generated-assets';`,
    '',
    'startStandaloneServer(EMBEDDED_ASSETS).catch((err) => {',
    '  console.error("Failed to start LumenTV:", err);',
    '  process.exit(1);',
    '});',
    '',
  ].join('\n');
  fs.writeFileSync(generatedEntryPath, entrySource, 'utf8');

  console.log(`Embedded ${files.length} LumenTV static assets into ${path.relative(rootDir, generatedAssetsPath)}`);
}

function ensureRootDependencies(requireFromRoot) {
  const required = ['vite', 'hls.js'];
  const missing = required.filter((pkg) => {
    try {
      requireFromRoot.resolve(pkg);
      return false;
    } catch {
      return true;
    }
  });

  if (missing.length > 0) {
    console.error(
      `Missing root dependencies in node_modules: ${missing.join(', ')}.\n` +
        'Run "npm install" (or "npm ci") in the repository root first, then re-run "npm run lumentv:build".'
    );
    process.exit(1);
  }
}

function resolveBunExecutable() {
  const candidates = [
    process.env.BUN_BIN,
    'bun',
    path.join(os.homedir(), '.bun', 'bin', process.platform === 'win32' ? 'bun.exe' : 'bun'),
  ].filter(Boolean);

  for (const candidate of candidates) {
    try {
      execFileSync(candidate, ['--version'], { stdio: 'ignore' });
      return candidate;
    } catch {
      // try next candidate
    }
  }

  console.error(
    'Bun runtime was not found on PATH (or ~/.bun/bin/bun).\n' +
      'Install Bun (https://bun.sh) to compile the standalone LumenTV binary.'
  );
  process.exit(1);
}

function main() {
  const opts = parseCliFlags(process.argv.slice(2));
  const requireFromRoot = createRequire(path.join(rootDir, 'package.json'));

  if (!opts.skipVite) {
    ensureRootDependencies(requireFromRoot);
    console.log('Building LumenTV standalone web bundle...');
    execFileSync(
      'npx',
      ['vite', 'build', '--config', 'graveyard/lumentv/vite.standalone.config.ts'],
      { cwd: rootDir, stdio: 'inherit' }
    );
  }

  generateEntryModules();

  const bunBin = resolveBunExecutable();

  if (opts.bundleOnly) {
    const bundlePath = opts.outfile || path.join(outBaseDir, 'lumentv.mjs');
    fs.mkdirSync(path.dirname(bundlePath), { recursive: true });
    execFileSync(
      bunBin,
      ['build', generatedEntryPath, '--target=bun', '--minify', '--outfile', bundlePath],
      { cwd: rootDir, stdio: 'inherit' }
    );
    console.log(`Built standalone bundle: ${path.relative(rootDir, bundlePath)}`);
    return;
  }

  const isWinTarget =
    opts.target.includes('windows') || (!opts.target && process.platform === 'win32');
  const defaultName = isWinTarget ? 'lumentv.exe' : 'lumentv';
  const binaryPath = opts.outfile || path.join(outBaseDir, defaultName);
  fs.mkdirSync(path.dirname(binaryPath), { recursive: true });

  const bunArgs = ['build', generatedEntryPath, '--compile', '--minify', '--outfile', binaryPath];
  if (opts.target) {
    bunArgs.push(`--target=${opts.target}`);
  }

  console.log(`Compiling LumenTV executable (${opts.target || 'host target'})...`);
  execFileSync(bunBin, bunArgs, { cwd: rootDir, stdio: 'inherit' });
  console.log(`Built executable: ${path.relative(rootDir, binaryPath)}`);
}

main();
